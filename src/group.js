// Finite groups, held by their elements.
//
// A Group lists every one of its elements, numbers them 0, 1, …, n−1 with the
// identity as 0, and does its work on those numbers through a multiplication
// table. That limits it to groups of a few thousand elements, which is what
// the questions a student asks of a group (its classes, subgroups, quotients,
// Sylow subgroups, homomorphisms) need. Elements themselves can be anything:
// numbers, permutations, matrices, tuples, cosets. A group knows how to
// multiply them, how to give each a key (equal elements, equal keys), and how
// to print them.
//
// Products are written left to right: mul(a, b) is ab. Conjugation is
// g·x·g⁻¹ and the commutator is [a, b] = a⁻¹b⁻¹ab.

const DEFAULT_MAX = 20000; // largest group generate() will build
const TABLE_MAX = 2048; // largest group that keeps a full multiplication table

export const defaultKey = (x) => (typeof x === "number" || typeof x === "string" || typeof x === "bigint" ? String(x) : JSON.stringify(x));

function gcd(a, b) {
  while (b) [a, b] = [b, a % b];
  return a;
}

function factorInt(n) {
  const out = new Map();
  for (let p = 2; p * p <= n; p += 1) while (n % p === 0) { out.set(p, (out.get(p) ?? 0) + 1); n /= p; }
  if (n > 1) out.set(n, (out.get(n) ?? 0) + 1);
  return out;
}
export { factorInt, gcd };

const isPrime = (p) => Number.isInteger(p) && p >= 2 && factorInt(p).size === 1 && factorInt(p).get(p) === 1;
export { isPrime };

export class Group {
  #key;
  #format;
  #mulValue;
  #index;
  #table = null;
  #inv = null;
  #orders = null;
  #tree = null;
  #classes = null;
  #subgroups = null;
  #normals = null;
  #masks = new WeakMap();
  #parentIndex = null; // this element number → parent's element number (subgroups)
  #fromParent = null; // parent's element number → this element number, or −1

  /**
   * Use Group.generate, Group.fromElements, or the named constructors; this is
   * the shared constructor and expects `elements` with the identity first.
   */
  constructor({ elements, mul, key = defaultKey, format = String, name = null, generators = null, parent = null, parentIndex = null, labels = null }) {
    this.#key = key;
    this.#format = format;
    this.#mulValue = mul;
    this.elements = Object.freeze(elements);
    this.order = elements.length;
    this.#index = new Map(elements.map((x, i) => [key(x), i]));
    if (this.#index.size !== elements.length) throw new Error("two of the listed elements have the same key");
    this.name = name;
    this.parent = parent;
    if (parent) {
      this.#parentIndex = Int32Array.from(parentIndex);
      this.#fromParent = new Int32Array(parent.order).fill(-1);
      this.#parentIndex.forEach((p, i) => { this.#fromParent[p] = i; });
    }
    this.labels = labels;
    this.gens = Int32Array.from(generators ?? this.#smallGenerators());
    if (this.order > 1 && this.gens.length === 0) throw new Error("a nontrivial group needs generators");
  }

  /**
   * The group generated by some elements under a multiplication.
   * `identity` is needed when there are no generators. Throws past `maxOrder`.
   */
  static generate({ generators, mul, identity, key = defaultKey, format = String, name = null, maxOrder = DEFAULT_MAX, labels = null }) {
    if (identity === undefined) {
      if (!generators.length) throw new Error("the trivial group needs its identity");
      // the identity is the power of a generator that comes back round
      const g = generators[0];
      let x = g;
      for (let i = 0; i <= maxOrder; i += 1) {
        const y = mul(x, g);
        if (key(y) === key(g)) { identity = x; break; }
        x = y;
      }
      if (identity === undefined) throw new RangeError(`a generator has order above ${maxOrder}`);
    }
    const elements = [identity];
    const seen = new Map([[key(identity), 0]]);
    for (let i = 0; i < elements.length; i += 1) {
      for (const s of generators) {
        const y = mul(elements[i], s);
        const k = key(y);
        if (seen.has(k)) continue;
        seen.set(k, elements.length);
        elements.push(y);
        if (elements.length > maxOrder) throw new RangeError(`the group has more than ${maxOrder} elements`);
      }
    }
    const gens = [];
    for (const s of generators) {
      const i = seen.get(key(s));
      if (i !== 0 && !gens.includes(i)) gens.push(i);
    }
    return new Group({ elements, mul, key, format, name, generators: gens, labels });
  }

  /** A group whose elements are all known already (identity anywhere in the list). */
  static fromElements(elements, mul, { key = defaultKey, format = String, name = null, generators = null, identity, labels = null } = {}) {
    const keys = elements.map(key);
    let e = identity === undefined ? -1 : keys.indexOf(key(identity));
    if (e < 0) e = elements.findIndex((x) => key(mul(x, x)) === key(x));
    if (e < 0) throw new Error("no identity among the elements");
    const order = [e, ...elements.keys()].filter((i, j) => j === 0 || i !== e);
    const els = order.map((i) => elements[i]);
    const gens = generators ? generators.map((g) => { const i = order.indexOf(keys.indexOf(key(g))); if (i < 0) throw new RangeError(`generator ${format(g)} is not among the elements`); return i; }).filter((i) => i > 0) : null;
    return new Group({ elements: els, mul, key, format, name, generators: gens, labels });
  }

  /**
   * A group from its multiplication table: table[i][j] is the number of the
   * product of elements i and j. Checks the group axioms (associativity in
   * full when n ≤ 64, or always with check: true).
   */
  static fromTable(table, { labels = null, name = null, check } = {}) {
    const n = table.length;
    if (!n || table.some((r) => r.length !== n || r.some((x) => !Number.isInteger(x) || x < 0 || x >= n))) throw new RangeError("a group table is an n×n array of numbers 0 … n−1");
    const e = table.findIndex((r, i) => r.every((x, j) => x === j) && table.every((rr) => rr[i] === table.indexOf(rr)));
    if (e < 0) throw new Error("the table has no identity");
    for (let i = 0; i < n; i += 1) if (!table[i].includes(e)) throw new Error(`element ${labels ? labels[i] : i} has no inverse`);
    for (let i = 0; i < n; i += 1) if (new Set(table[i]).size !== n) throw new Error("a row of the table repeats an element");
    if (check ?? n <= 64) {
      for (let a = 0; a < n; a += 1) for (let b = 0; b < n; b += 1) for (let c = 0; c < n; c += 1) {
        if (table[table[a][b]][c] !== table[a][table[b][c]]) throw new Error(`the table is not associative: (${a}·${b})·${c} ≠ ${a}·(${b}·${c})`);
      }
    }
    const vals = labels ? [...labels] : [...Array(n).keys()];
    const idx = new Map(vals.map((v, i) => [defaultKey(v), i]));
    return Group.fromElements(vals, (a, b) => vals[table[idx.get(defaultKey(a))][idx.get(defaultKey(b))]], { name, identity: vals[e] });
  }

  // ---- elements ------------------------------------------------------------------------------------

  /** The element number of x (a value, a label, or an element number marked with { index }). */
  indexOf(x) {
    if (x !== null && typeof x === "object" && !Array.isArray(x) && Number.isInteger(x.index) && Object.keys(x).length === 1) return x.index;
    const i = this.#index.get(this.#key(x));
    if (i !== undefined) return i;
    if (typeof x === "string") {
      const j = this.#labelIndex(x);
      if (j >= 0) return j;
    }
    return -1;
  }

  #labelMap = null;
  #labelIndex(s) {
    if (!this.#labelMap) {
      this.#labelMap = new Map();
      this.elements.forEach((x, i) => this.#labelMap.set(norm(this.#format(x)), i));
      if (this.labels) for (const [lab, v] of Object.entries(this.labels)) { const i = this.#index.get(this.#key(v)); if (i !== undefined) this.#labelMap.set(norm(lab), i); }
    }
    return this.#labelMap.get(norm(s)) ?? -1;
  }

  #i(x) {
    const i = this.indexOf(x);
    if (i < 0) throw new RangeError(`${typeof x === "string" ? x : this.#safeFormat(x)} is not an element of ${this.toString()}`);
    return i;
  }

  #safeFormat(x) {
    try { return this.#format(x); } catch { return defaultKey(x); }
  }

  /** The element itself, from a value or a printed label such as "r²s" or "(1 2 3)". */
  element(x) { return this.elements[this.#i(x)]; }
  has(x) { return this.indexOf(x) >= 0; }
  key(x) { return this.#key(x); }
  format(x) { return this.#format(x); }
  get identity() { return this.elements[0]; }
  get generators() { return [...this.gens].map((i) => this.elements[i]); }

  /** Multiplication on element numbers. */
  mulIndex(i, j) {
    if (this.#table) return this.#table[i * this.order + j];
    if (this.parent) return this.#fromParent[this.parent.mulIndex(this.#parentIndex[i], this.#parentIndex[j])];
    if (this.order <= TABLE_MAX) {
      this.#buildTable();
      return this.#table[i * this.order + j];
    }
    const k = this.#index.get(this.#key(this.#mulValue(this.elements[i], this.elements[j])));
    if (k === undefined) throw new Error("the multiplication left the group");
    return k;
  }

  #buildTable() {
    const n = this.order;
    const T = n <= 65535 ? new Uint16Array(n * n) : new Uint32Array(n * n);
    for (let i = 0; i < n; i += 1) {
      for (let j = 0; j < n; j += 1) {
        let k;
        if (this.parent) k = this.#fromParent[this.parent.mulIndex(this.#parentIndex[i], this.#parentIndex[j])];
        else k = this.#index.get(this.#key(this.#mulValue(this.elements[i], this.elements[j])));
        if (k === undefined || k < 0) throw new Error("the multiplication left the group");
        T[i * n + j] = k;
      }
    }
    this.#table = T;
  }

  invIndex(i) {
    if (!this.#inv) {
      const n = this.order;
      const inv = new Int32Array(n).fill(-1);
      for (let x = 0; x < n; x += 1) {
        if (inv[x] >= 0) continue;
        // walk the powers of x until they come back to the identity
        let p = x;
        let prev = 0;
        while (p !== 0) { prev = p; p = this.mulIndex(p, x); }
        // x^(k−1) is the inverse, where x^k = e; prev = x^(k−1)
        inv[x] = prev;
        inv[prev] = x;
      }
      inv[0] = 0;
      this.#inv = inv;
    }
    return this.#inv[i];
  }

  powIndex(i, k) {
    if (k < 0) return this.powIndex(this.invIndex(i), -k);
    let r = 0;
    let b = i;
    while (k > 0) {
      if (k & 1) r = this.mulIndex(r, b);
      b = this.mulIndex(b, b);
      k = Math.floor(k / 2);
    }
    return r;
  }

  mul(...xs) { return this.elements[xs.reduce((r, x) => this.mulIndex(r, this.#i(x)), 0)]; }
  inv(x) { return this.elements[this.invIndex(this.#i(x))]; }
  pow(x, k) { return this.elements[this.powIndex(this.#i(x), Number(k))]; }
  /** g·x·g⁻¹. */
  conjugate(x, g) { const gi = this.#i(g); return this.elements[this.mulIndex(this.mulIndex(gi, this.#i(x)), this.invIndex(gi))]; }
  /** [a, b] = a⁻¹b⁻¹ab. */
  commutator(a, b) { return this.elements[this.#comm(this.#i(a), this.#i(b))]; }
  #comm(a, b) { return this.mulIndex(this.mulIndex(this.invIndex(a), this.invIndex(b)), this.mulIndex(a, b)); }
  equal(a, b) { return this.#i(a) === this.#i(b); }

  /** The order of an element: the least k ≥ 1 with x^k = e. */
  elementOrder(x) { return this.#orderIndex(this.#i(x)); }
  #orderIndex(i) {
    if (!this.#orders) {
      const o = new Int32Array(this.order);
      for (let x = 0; x < this.order; x += 1) {
        let k = 1;
        for (let p = x; p !== 0; p = this.mulIndex(p, x)) k += 1;
        o[x] = k;
      }
      this.#orders = o;
    }
    return this.#orders[i];
  }
  orderIndex(i) { return this.#orderIndex(i); }

  /** How many elements have each order: a Map order → count, smallest order first. */
  orderStatistics() {
    const m = new Map();
    for (let i = 0; i < this.order; i += 1) m.set(this.#orderIndex(i), (m.get(this.#orderIndex(i)) ?? 0) + 1);
    return new Map([...m].sort((a, b) => a[0] - b[0]));
  }

  /** The least common multiple of the element orders. */
  get exponent() {
    let l = 1;
    for (let i = 0; i < this.order; i += 1) { const o = this.#orderIndex(i); l = (l / gcd(l, o)) * o; }
    return l;
  }

  get isAbelian() {
    const g = this.gens;
    for (const a of g) for (const b of g) if (this.mulIndex(a, b) !== this.mulIndex(b, a)) return false;
    return true;
  }
  get isCyclic() { for (let i = 0; i < this.order; i += 1) if (this.#orderIndex(i) === this.order) return true; return false; }
  get isTrivial() { return this.order === 1; }
  /** True when the order is a power of a prime (the trivial group counts). */
  get isPGroup() { return factorInt(this.order).size <= 1; }

  /**
   * The Cayley table: { labels, table } with table[i][j] the number of the
   * product of elements i and j, printed as a grid by toString().
   */
  cayleyTable({ order = null } = {}) {
    const idx = order ? order.map((x) => this.#i(x)) : [...Array(this.order).keys()];
    const pos = new Map(idx.map((x, i) => [x, i]));
    const labels = idx.map((i) => this.#format(this.elements[i]));
    const table = idx.map((a) => idx.map((b) => pos.get(this.mulIndex(a, b))));
    const w = Math.max(...labels.map((s) => [...s].length));
    const pad = (s) => s + " ".repeat(w - [...s].length);
    return Object.freeze({
      labels,
      elements: idx.map((i) => this.elements[i]),
      table,
      toString: () => [`${pad("·")} │ ${labels.map(pad).join(" ")}`, `${"─".repeat(w)}─┼─${"─".repeat((w + 1) * labels.length - 1)}`, ...table.map((r, i) => `${pad(labels[i])} │ ${r.map((j) => pad(labels[j])).join(" ")}`)].join("\n"),
    });
  }

  // ---- subgroups as element sets ---------------------------------------------------------------------

  /** The element numbers, in this group, of a subgroup (or any group whose elements lie in this one). */
  maskOf(H) {
    if (H === this) return new Uint8Array(this.order).fill(1);
    let m = this.#masks.get(H);
    if (m) return m;
    m = new Uint8Array(this.order);
    if (H.parent === this) for (const p of H.parentIndices()) m[p] = 1;
    else for (const x of H.elements) { const i = this.indexOf(x); if (i < 0) throw new RangeError(`${H} is not inside ${this}`); m[i] = 1; }
    this.#masks.set(H, m);
    return m;
  }

  parentIndices() { return this.#parentIndex ? [...this.#parentIndex] : [...Array(this.order).keys()]; }
  /** For a subgroup: the element number in the parent of the element numbered i here. */
  toParentIndex(i) { return this.#parentIndex ? this.#parentIndex[i] : i; }

  /** The subgroup on a set of element numbers already known to be closed (identity included). */
  subgroupFromIndices(list, gens = null, name = null) {
    const L = [...list].sort((a, b) => a - b);
    if (L[0] !== 0) throw new Error("internal: a subgroup without the identity");
    if (L.length === this.order && !this.parent) return this;
    const pos = new Map(L.map((x, i) => [x, i]));
    const g = gens ? gens.map((x) => pos.get(x)).filter((i) => i > 0) : null;
    return new Group({ elements: L.map((i) => this.elements[i]), mul: this.#mulValue, key: this.#key, format: this.#format, name, generators: g, parent: this, parentIndex: L });
  }

  /** Closure of a set of element numbers under multiplication: the element numbers of the subgroup they generate. */
  closeIndices(gens) {
    const inside = new Uint8Array(this.order);
    inside[0] = 1;
    const list = [0];
    for (let i = 0; i < list.length; i += 1) {
      for (const s of gens) {
        const y = this.mulIndex(list[i], s);
        if (!inside[y]) { inside[y] = 1; list.push(y); }
      }
    }
    return { list, inside };
  }

  /** The subgroup generated by some elements. */
  subgroup(generators, { name = null } = {}) {
    const gens = generators.map((g) => this.#i(g));
    return this.subgroupFromIndices(this.closeIndices(gens).list, gens, name);
  }

  /** The trivial subgroup and the whole group as a subgroup of itself. */
  trivialSubgroup() { return this.subgroupFromIndices([0], [], "1"); }

  /** Is H (any group whose elements multiply the same way) a subgroup of this group? */
  isSubgroup(H) {
    const idx = [];
    for (const x of H.elements) { const i = this.indexOf(x); if (i < 0) return false; idx.push(i); }
    const set = new Set(idx);
    if (!set.has(0)) return false;
    for (const a of idx) for (const b of H.gens) if (!set.has(this.mulIndex(a, this.indexOf(H.elements[b])))) return false;
    return true;
  }

  /** Same elements? */
  equals(H) {
    if (H.order !== this.order) return false;
    for (const x of H.elements) if (this.indexOf(x) < 0) return false;
    return true;
  }

  contains(H) { return H.elements.every((x) => this.indexOf(x) >= 0); }
  index(H) { return this.order / this.#sub(H).order; }

  #sub(H) {
    if (Array.isArray(H)) return this.subgroup(H);
    if (!(H instanceof Group)) throw new TypeError("expected a subgroup");
    return H;
  }

  intersection(H, K) {
    const a = this.maskOf(this.#sub(H));
    const b = this.maskOf(this.#sub(K));
    const list = [];
    for (let i = 0; i < this.order; i += 1) if (a[i] && b[i]) list.push(i);
    return this.subgroupFromIndices(list);
  }

  /** The subgroup generated by H and K together. */
  join(...Hs) {
    const gens = [];
    for (const H of Hs) for (const g of this.#sub(H).generators) gens.push(this.#i(g));
    return this.subgroupFromIndices(this.closeIndices(gens).list, gens);
  }

  /** The set HK = { hk }, as values; a subgroup exactly when HK = KH. */
  product(H, K) {
    const a = this.#sub(H).elements.map((x) => this.#i(x));
    const b = this.#sub(K).elements.map((x) => this.#i(x));
    const set = new Set();
    for (const x of a) for (const y of b) set.add(this.mulIndex(x, y));
    return [...set].sort((x, y) => x - y).map((i) => this.elements[i]);
  }

  // ---- centres, centralisers, normalisers --------------------------------------------------------------

  /** Z(G): the elements that commute with everything. */
  centre() {
    const list = [];
    for (let z = 0; z < this.order; z += 1) if ([...this.gens].every((g) => this.mulIndex(z, g) === this.mulIndex(g, z))) list.push(z);
    return this.subgroupFromIndices(list, null, "Z");
  }
  center() { return this.centre(); }

  /** C(S): the elements commuting with an element, a list of elements, or every element of a subgroup. */
  centraliser(S) {
    const s = S instanceof Group ? S.generators.map((x) => this.#i(x)) : Array.isArray(S) && !this.has(S) ? S.map((x) => this.#i(x)) : [this.#i(S)];
    const list = [];
    for (let g = 0; g < this.order; g += 1) if (s.every((x) => this.mulIndex(g, x) === this.mulIndex(x, g))) list.push(g);
    return this.subgroupFromIndices(list);
  }
  centralizer(S) { return this.centraliser(S); }

  /** N(H): the elements g with gHg⁻¹ = H. */
  normaliser(H) {
    H = this.#sub(H);
    const m = this.maskOf(H);
    const hs = H.generators.map((x) => this.#i(x));
    const list = [];
    for (let g = 0; g < this.order; g += 1) {
      const gi = this.invIndex(g);
      if (hs.every((h) => m[this.mulIndex(this.mulIndex(g, h), gi)])) list.push(g);
    }
    return this.subgroupFromIndices(list);
  }
  normalizer(H) { return this.normaliser(H); }

  /** Is H normal in this group (gHg⁻¹ = H for every g)? */
  isNormal(H) {
    H = this.#sub(H);
    const m = this.maskOf(H);
    const hs = H.generators.map((x) => this.#i(x));
    return [...this.gens].every((g) => { const gi = this.invIndex(g); return hs.every((h) => m[this.mulIndex(this.mulIndex(g, h), gi)]); });
  }

  /** gHg⁻¹, as a subgroup. */
  conjugateSubgroup(H, g) {
    H = this.#sub(H);
    const gi = this.#i(g);
    const ginv = this.invIndex(gi);
    const list = H.elements.map((x) => this.mulIndex(this.mulIndex(gi, this.#i(x)), ginv));
    return this.subgroupFromIndices(list);
  }

  /** The smallest normal subgroup containing the given elements. */
  normalClosure(S) {
    const start = S instanceof Group ? S.generators.map((x) => this.#i(x)) : S.map((x) => this.#i(x));
    return this.subgroupFromIndices(this.#normalClosureIndices(start).list);
  }

  #normalClosureIndices(start) {
    let gens = start.filter((x) => x !== 0);
    let H = this.closeIndices(gens);
    for (;;) {
      const extra = [];
      for (const g of this.gens) {
        const gi = this.invIndex(g);
        for (const h of gens) {
          const c = this.mulIndex(this.mulIndex(g, h), gi);
          if (!H.inside[c] && !extra.includes(c)) extra.push(c);
        }
      }
      if (!extra.length) return H;
      gens = [...gens, ...extra];
      H = this.closeIndices(gens);
    }
  }

  // ---- conjugacy classes ---------------------------------------------------------------------------

  /**
   * The conjugacy classes: [{ representative, elements, size, order }] with the
   * identity's class first, then by element order and size. `order` is the
   * order of each element of the class; size·|C(x)| = |G|.
   */
  conjugacyClasses() {
    if (this.#classes) return this.#classes;
    const cls = new Int32Array(this.order).fill(-1);
    const out = [];
    for (let x = 0; x < this.order; x += 1) {
      if (cls[x] >= 0) continue;
      const list = [x];
      cls[x] = out.length;
      for (let i = 0; i < list.length; i += 1) {
        for (const g of this.gens) {
          const y = this.mulIndex(this.mulIndex(g, list[i]), this.invIndex(g));
          if (cls[y] < 0) { cls[y] = out.length; list.push(y); }
        }
      }
      list.sort((a, b) => a - b);
      out.push(list);
    }
    this.classOfIndex = cls;
    const res = out.map((list) => Object.freeze({ representative: this.elements[list[0]], elements: list.map((i) => this.elements[i]), indices: list, size: list.length, order: this.#orderIndex(list[0]) }));
    res.sort((a, b) => a.order - b.order || a.size - b.size || a.indices[0] - b.indices[0]);
    this.#classes = Object.freeze(res);
    return this.#classes;
  }

  /** The class equation |G| = |Z(G)| + Σ [G : C(xᵢ)], as { order, centre, terms, toString }. */
  classEquation() {
    const cl = this.conjugacyClasses();
    const centre = cl.filter((c) => c.size === 1).length;
    const terms = cl.filter((c) => c.size > 1).map((c) => c.size).sort((a, b) => a - b);
    return Object.freeze({ order: this.order, centre, terms, toString: () => `${this.order} = ${[centre, ...terms].join(" + ")}` });
  }

  // ---- commutators and series ----------------------------------------------------------------------

  /** G′ = [G, G], the subgroup generated by all commutators. */
  derivedSubgroup() {
    const c = [];
    for (const a of this.gens) for (const b of this.gens) c.push(this.#comm(a, b));
    return this.subgroupFromIndices(this.#normalClosureIndices(c).list, null, "G′");
  }
  commutatorSubgroup() { return this.derivedSubgroup(); }

  /** [H, K]: generated by the commutators [h, k]; both should be normal, or H, K with H ⊆ N(K). */
  commutatorOf(H, K) {
    H = this.#sub(H); K = this.#sub(K);
    const c = [];
    for (const h of H.generators) for (const k of K.generators) c.push(this.#comm(this.#i(h), this.#i(k)));
    // the normal closure in ⟨H, K⟩
    const J = this.join(H, K);
    const inJ = J.#normalClosureIndices(c.map((x) => J.indexOf(this.elements[x]))).list.map((i) => this.indexOf(J.elements[i]));
    return this.subgroupFromIndices(inJ);
  }

  #lift(K) { return K === this ? this : this.subgroupFromIndices(K.elements.map((x) => this.#i(x))); }

  /** G ⊇ G′ ⊇ G″ ⊇ … until it stops; all subgroups of this group. */
  derivedSeries() {
    const out = [this];
    for (;;) {
      const last = out[out.length - 1];
      const next = this.#lift(last.derivedSubgroup());
      if (next.order === last.order) return out;
      out.push(next);
    }
  }

  /** γ₁ = G, γᵢ₊₁ = [γᵢ, G], until it stops. */
  lowerCentralSeries() {
    const out = [this];
    for (;;) {
      const last = out[out.length - 1];
      const c = [];
      for (const x of last.generators) for (const g of this.gens) c.push(this.#comm(this.#i(x), g));
      const next = this.subgroupFromIndices(this.#normalClosureIndices(c).list);
      if (next.order === last.order) return out;
      out.push(next);
    }
  }

  /** 1 = Z₀ ⊆ Z₁ = Z(G) ⊆ Z₂ ⊆ …, Zᵢ₊₁ = { x : [x, g] ∈ Zᵢ for all g }, until it stops. */
  upperCentralSeries() {
    const out = [this.trivialSubgroup()];
    for (;;) {
      const m = this.maskOf(out[out.length - 1]);
      const list = [];
      for (let x = 0; x < this.order; x += 1) if ([...this.gens].every((g) => m[this.#comm(x, g)])) list.push(x);
      if (list.length === out[out.length - 1].order) return out;
      out.push(this.subgroupFromIndices(list));
    }
  }

  get isSolvable() { const s = this.derivedSeries(); return s[s.length - 1].order === 1; }
  get isNilpotent() { const s = this.upperCentralSeries(); return s[s.length - 1].order === this.order; }
  /** Nilpotency class (length of the lower central series to 1), or null if not nilpotent. */
  get nilpotencyClass() { const s = this.lowerCentralSeries(); return s[s.length - 1].order === 1 ? s.length - 1 : null; }
  get isSimple() { return this.order > 1 && this.normalSubgroups().length === 2; }
  get isPerfect() { return this.derivedSubgroup().order === this.order; }

  // ---- all subgroups ---------------------------------------------------------------------------------

  /**
   * Every subgroup, smallest first. Builds them by joining cyclic subgroups
   * layer by layer, so it refuses groups larger than `maxOrder` (default 1000).
   */
  subgroups({ maxOrder = 1000 } = {}) {
    if (this.#subgroups) return this.#subgroups;
    if (this.order > maxOrder) throw new RangeError(`listing all subgroups of a group of order ${this.order} is too much work (maxOrder ${maxOrder})`);
    const id = (list) => list.join(",");
    const cyclic = new Map();
    for (let i = 1; i < this.order; i += 1) {
      const C = this.closeIndices([i]);
      const k = id(C.list.sort((a, b) => a - b));
      if (!cyclic.has(k)) cyclic.set(k, i);
    }
    const trivial = { gens: [], inside: Uint8Array.of(1, ...new Uint8Array(this.order - 1)), list: [0] };
    const found = new Map([["0", trivial]]);
    let layer = [trivial];
    while (layer.length) {
      const next = [];
      for (const H of layer) {
        for (const g of cyclic.values()) {
          if (H.inside[g]) continue;
          const gens = [...H.gens, g];
          const C = this.closeIndices(gens);
          const k = id(C.list.sort((a, b) => a - b));
          if (found.has(k)) continue;
          const K = { gens, inside: C.inside, list: C.list };
          found.set(k, K);
          next.push(K);
        }
      }
      layer = next;
    }
    this.#subgroups = Object.freeze([...found.values()].map((H) => this.subgroupFromIndices(H.list, H.gens)).sort((a, b) => a.order - b.order));
    return this.#subgroups;
  }

  /**
   * Subgroups up to conjugacy: [{ group, order, index, conjugates, normal }],
   * smallest first; `conjugates` is how many subgroups the class holds.
   */
  subgroupClasses(options) {
    const subs = this.subgroups(options);
    const sig = (H) => H.parentIndices().join(",");
    const byId = new Map(subs.map((H) => [sig(H), H]));
    const seen = new Set();
    const out = [];
    for (const H of subs) {
      if (seen.has(sig(H))) continue;
      const cls = new Set();
      const hs = H.parentIndices();
      for (let g = 0; g < this.order; g += 1) {
        const gi = this.invIndex(g);
        cls.add(hs.map((h) => this.mulIndex(this.mulIndex(g, h), gi)).sort((a, b) => a - b).join(","));
      }
      cls.forEach((s) => seen.add(s));
      out.push(Object.freeze({ group: H, order: H.order, index: this.order / H.order, conjugates: cls.size, normal: cls.size === 1, members: [...cls].map((s) => byId.get(s)) }));
    }
    return Object.freeze(out);
  }

  /**
   * Every normal subgroup, smallest first. Built from the normal closures of
   * the conjugacy classes and their products, so it works without listing
   * all subgroups.
   */
  normalSubgroups() {
    if (this.#normals) return this.#normals;
    const id = (list) => [...list].sort((a, b) => a - b).join(",");
    const atoms = new Map();
    for (const c of this.conjugacyClasses()) {
      if (c.indices[0] === 0) continue;
      const N = this.#normalClosureIndices([c.indices[0]]);
      atoms.set(id(N.list), { gens: [c.indices[0]], ...N });
    }
    const trivial = { gens: [], list: [0], inside: Uint8Array.of(1, ...new Uint8Array(this.order - 1)) };
    const found = new Map([["0", trivial]]);
    let layer = [trivial];
    while (layer.length) {
      const next = [];
      for (const H of layer) {
        for (const A of atoms.values()) {
          if (A.list.every((x) => H.inside[x])) continue;
          const gens = [...H.gens, ...A.gens];
          const C = this.#normalClosureIndices(gens);
          const k = id(C.list);
          if (found.has(k)) continue;
          const K = { gens, ...C };
          found.set(k, K);
          next.push(K);
        }
      }
      layer = next;
    }
    this.#normals = Object.freeze([...found.values()].map((H) => this.subgroupFromIndices(H.list)).sort((a, b) => a.order - b.order));
    return this.#normals;
  }

  /** A composition series G = G₀ ⊳ G₁ ⊳ … ⊳ 1 and its simple factors' orders. */
  compositionSeries() {
    const series = [this];
    let H = this;
    while (H.order > 1) {
      const N = H.normalSubgroups();
      // a proper normal subgroup of largest order is a maximal one
      H = this.#lift(N[N.length - 2]);
      series.push(H);
    }
    const factors = [];
    for (let i = 0; i + 1 < series.length; i += 1) factors.push(series[i].order / series[i + 1].order);
    return Object.freeze({ series, factors, toString: () => series.map((S) => S.order).join(" ⊳ ") });
  }

  // ---- cosets and quotients --------------------------------------------------------------------------

  /** The left cosets gH (or right cosets Hg with side: "right"): [{ representative, elements }]. */
  cosets(H, { side = "left" } = {}) {
    H = this.#sub(H);
    const hs = H.elements.map((x) => this.#i(x));
    const seen = new Uint8Array(this.order);
    const out = [];
    for (let g = 0; g < this.order; g += 1) {
      if (seen[g]) continue;
      const list = hs.map((h) => (side === "right" ? this.mulIndex(h, g) : this.mulIndex(g, h))).sort((a, b) => a - b);
      list.forEach((x) => { seen[x] = 1; });
      out.push(Object.freeze({ representative: this.elements[g], elements: list.map((i) => this.elements[i]), indices: list }));
    }
    return out;
  }

  /** G/N for a normal subgroup N: its elements are cosets, printed as gN. */
  quotient(N, { name = null } = {}) {
    N = this.#sub(N);
    if (!this.isNormal(N)) throw new RangeError(`${N} is not a normal subgroup, so the cosets do not form a group`);
    const cs = this.cosets(N);
    const of = new Int32Array(this.order);
    cs.forEach((c, i) => c.indices.forEach((x) => { of[x] = i; }));
    const nName = N.name ?? "N";
    const fmt = this.#format;
    const cosets = cs.map((c, i) => new Coset(i, c.indices[0], c.indices, nName, fmt(this.elements[c.indices[0]])));
    const G = this;
    const Q = new Group({
      elements: cosets,
      mul: (a, b) => cosets[of[G.mulIndex(a.repIndex, b.repIndex)]],
      key: (c) => (c instanceof Coset ? `c${c.id}` : `?${defaultKey(c)}`),
      format: (c) => c.toString(),
      name: name ?? (this.name && N.name ? `${this.name}/${N.name}` : null),
      generators: [...new Set([...this.gens].map((g) => of[g]))].filter((i) => i > 0),
    });
    Q.cosetOf = (x) => cosets[of[this.#i(x)]];
    Q.over = this;
    Q.normal = N;
    return Q;
  }

  // ---- Sylow subgroups -------------------------------------------------------------------------------

  /**
   * A Sylow p-subgroup: a subgroup of order p^a, where p^a is the largest
   * power of p dividing |G|. Grows a p-subgroup P inside its normaliser,
   * which always has an element of p-power order outside P until P is Sylow.
   */
  sylowSubgroup(p) {
    if (!isPrime(p)) throw new RangeError(`${p} is not a prime`);
    let target = 1;
    while (this.order % (target * p) === 0) target *= p;
    let P = { list: [0], inside: Uint8Array.of(1, ...new Uint8Array(this.order - 1)), gens: [] };
    while (P.list.length < target) {
      const Pg = this.subgroupFromIndices(P.list, P.gens);
      const N = this.maskOf(this.normaliser(Pg));
      let grown = null;
      for (let x = 1; x < this.order && !grown; x += 1) {
        if (!N[x] || P.inside[x]) continue;
        let k = 1;
        let y = x;
        while (!P.inside[y]) { y = this.mulIndex(y, x); k += 1; }
        if (factorInt(k).size === 1 && factorInt(k).has(p)) {
          const gens = [...P.gens, x];
          grown = { ...this.closeIndices(gens), gens };
        }
      }
      if (!grown) throw new Error("internal: no p-element in the normaliser (Sylow's theorem says there is one)");
      P = grown;
    }
    return this.subgroupFromIndices(P.list, P.gens, `Syl${p}`);
  }

  /** All Sylow p-subgroups: the conjugates of one of them. */
  sylowSubgroups(p) {
    const P = this.sylowSubgroup(p);
    const seen = new Map();
    for (let g = 0; g < this.order; g += 1) {
      const C = this.conjugateSubgroup(P, this.elements[g]);
      const k = C.parentIndices().join(",");
      if (!seen.has(k)) seen.set(k, C);
    }
    return [...seen.values()];
  }

  /** n_p, the number of Sylow p-subgroups, as [G : N(P)]. */
  sylowCount(p) { return this.order / this.normaliser(this.sylowSubgroup(p)).order; }

  // ---- printing ---------------------------------------------------------------------------------------

  toString() {
    if (this.name) return this.name;
    const g = this.generators.map((x) => this.#format(x));
    return `⟨${g.join(", ")}⟩`;
  }

  /** A short description: name, order, and a few invariants. */
  describe() {
    const bits = [`order ${this.order}`];
    if (this.isAbelian) bits.push(this.isCyclic ? "cyclic" : "abelian");
    else bits.push("nonabelian");
    bits.push(`${this.conjugacyClasses().length} classes`, `centre of order ${this.centre().order}`);
    return `${this} (${bits.join(", ")})`;
  }

  #smallGenerators() {
    // greedy: add the element that grows the generated subgroup most
    const gens = [];
    let H = this.#closeNoTable([]);
    while (H.list.length < this.order) {
      let best = null;
      for (let x = this.order - 1; x > 0; x -= 1) {
        if (H.inside[x]) continue;
        const K = this.#closeNoTable([...gens, x]);
        if (!best || K.list.length > best.K.list.length) best = { x, K };
        if (best.K.list.length === this.order) break;
      }
      gens.push(best.x);
      H = best.K;
    }
    return gens;
  }

  #closeNoTable(gens) {
    // used while the constructor is still running (this.gens not set yet)
    const inside = new Uint8Array(this.order);
    inside[0] = 1;
    const list = [0];
    for (let i = 0; i < list.length; i += 1) for (const s of gens) {
      const y = this.mulIndex(list[i], s);
      if (!inside[y]) { inside[y] = 1; list.push(y); }
    }
    return { list, inside };
  }

  /** For each element number (except 0) a pair [earlier element number, generator number] with x = earlier·generator. */
  spanningTree() {
    if (this.#tree) return this.#tree;
    const from = new Int32Array(this.order).fill(-1);
    const by = new Int32Array(this.order).fill(-1);
    const seen = new Uint8Array(this.order);
    seen[0] = 1;
    const queue = [0];
    for (let i = 0; i < queue.length; i += 1) {
      for (let s = 0; s < this.gens.length; s += 1) {
        const y = this.mulIndex(queue[i], this.gens[s]);
        if (!seen[y]) { seen[y] = 1; from[y] = queue[i]; by[y] = s; queue.push(y); }
      }
    }
    this.#tree = { order: queue, from, by };
    return this.#tree;
  }
}

/** An element of a quotient group: the coset gN, printed with its representative. */
export class Coset {
  constructor(id, repIndex, indices, nName, repText) {
    this.id = id;
    this.repIndex = repIndex;
    this.indices = indices;
    this.text = id === 0 ? nName : `${repText}${nName}`;
    Object.freeze(this);
  }
  toString() { return this.text; }
}

const SUP = { "0": "⁰", "1": "¹", "2": "²", "3": "³", "4": "⁴", "5": "⁵", "6": "⁶", "7": "⁷", "8": "⁸", "9": "⁹", "-": "⁻" };
export const sup = (k) => String(k).split("").map((c) => SUP[c] ?? c).join("");
/** Labels compare without spaces or "*", with x^2 and x² the same. */
const norm = (s) => String(s).replace(/\s+/g, "").replace(/\^\(?(-?\d+)\)?/g, (_, d) => sup(d)).replace(/\*/g, "");
