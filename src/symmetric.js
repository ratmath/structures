// Symmetric polynomials.
//
// A polynomial is symmetric when it does not change under any permutation of
// the variables. The fundamental theorem says every symmetric polynomial is,
// in exactly one way, a polynomial in the elementary symmetric polynomials
// e₁ = x₁ + … + xₙ, e₂ = Σ xᵢxⱼ, …, eₙ = x₁⋯xₙ. `toElementary` finds it.

import { PolyRing, MPoly } from "./mpoly.js";
import { keyOf } from "./monomial.js";

/** The k-th elementary symmetric polynomial of the ring's variables (e₀ = 1). */
export function elementary(R, k) {
  if (!Number.isInteger(k) || k < 0) throw new RangeError("k must be a non-negative integer");
  if (k > R.n) return R.zero;
  const m = new Map();
  const pick = (start, left, e) => {
    if (left === 0) {
      m.set(keyOf(e), { e: [...e], c: R.K.one });
      return;
    }
    for (let i = start; i <= R.n - left; i += 1) {
      e[i] = 1;
      pick(i + 1, left - 1, e);
      e[i] = 0;
    }
  };
  pick(0, k, new Array(R.n).fill(0));
  return new MPoly(R, m);
}

/** The k-th power sum x₁ᵏ + … + xₙᵏ. */
export function powerSum(R, k) {
  if (!Number.isInteger(k) || k < 0) throw new RangeError("k must be a non-negative integer");
  return R.gens.reduce((s, x) => s.add(x.pow(k)), R.zero);
}

/** The k-th complete homogeneous symmetric polynomial: the sum of all monomials of degree k. */
export function completeHomogeneous(R, k) {
  if (!Number.isInteger(k) || k < 0) throw new RangeError("k must be a non-negative integer");
  const m = new Map();
  const fill = (i, left, e) => {
    if (i === R.n - 1) {
      e[i] = left;
      m.set(keyOf(e), { e: [...e], c: R.K.one });
      return;
    }
    for (let a = 0; a <= left; a += 1) {
      e[i] = a;
      fill(i + 1, left - a, e);
    }
  };
  fill(0, k, new Array(R.n).fill(0));
  return new MPoly(R, m);
}

/** Whether f is unchanged by every permutation of the ring's variables. */
export function isSymmetric(f) {
  const R = f.ring;
  if (R.n < 2) return true;
  // the symmetric group is generated by one transposition and one n-cycle
  const apply = (perm) => {
    const m = new Map();
    for (const { e, c } of f._m.values()) {
      const ee = perm.map((p) => e[p]);
      m.set(keyOf(ee), { e: ee, c });
    }
    return new MPoly(R, m);
  };
  const swap = R.vars.map((_, i) => (i === 0 ? 1 : i === 1 ? 0 : i));
  const cycle = R.vars.map((_, i) => (i + 1) % R.n);
  return f.equals(apply(swap)) && f.equals(apply(cycle));
}

/**
 * Write a symmetric polynomial in terms of the elementary symmetric
 * polynomials. Returns { polynomial, ring }: a polynomial in new variables
 * e1, …, en (named with `prefix`) such that substituting the elementary
 * symmetric polynomials for them gives f back.
 *
 * The proof of the fundamental theorem is the algorithm: in lexicographic
 * order the leading monomial x₁^a₁⋯xₙ^aₙ of a symmetric polynomial has
 * a₁ ≥ … ≥ aₙ, and e₁^(a₁−a₂)·e₂^(a₂−a₃)⋯eₙ^aₙ has the same leading monomial.
 * Subtract the right multiple and repeat; the leading monomial drops each time.
 */
export function toElementary(f, { prefix = "e" } = {}) {
  const R = f.ring;
  if (!isSymmetric(f)) throw new RangeError(`${f} is not symmetric in ${R.vars.join(", ")}`);
  const L = R.order === "lex" ? R : R.withOrder("lex");
  const E = new PolyRing(R.vars.map((_, i) => `${prefix}${i + 1}`), { field: R.field, order: "grlex" });
  const es = R.vars.map((_, i) => elementary(L, i + 1));
  let rest = f.into(L);
  const m = new Map();
  while (!rest.isZero()) {
    const { e, c } = rest._lead();
    const exps = e.map((a, i) => a - (e[i + 1] ?? 0));
    let prod = L.constant(c);
    exps.forEach((k, i) => {
      if (k > 0) prod = prod.mul(es[i].pow(k));
    });
    rest = rest.sub(prod);
    m.set(keyOf(exps), { e: exps, c });
  }
  return { polynomial: new MPoly(E, m), ring: E };
}
